import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { runEngine } from './engine.js';
import type { EngineInvocation } from './engineSession.js';
import type { BarrierDependencySnapshot, EngineResponse } from './jobContracts.js';
import { supportedBarrierAdmissionIntentSchema, supportedBarrierRuntimeContextSchema } from '../../shared/pathfinderBarrierSupported.js';
import { MIXED_BARRIER_POLICY, mixedBarrierVerifierEvidenceSchema } from '../../shared/pathfinderBarrierMixed.js';
import { mixedBarrierCalculationEngineIdentity } from './calculationEngineIdentity.js';
import { syntheticBarrierWriteInputs } from './barrierWriteFixtures.js';

export type ManualRoutingNativeKind = 'happy' | 'opening' | 'blocked' | 'missing';
type Execution = { requestId: string; pid: number; status: EngineResponse['status']; requestPath: string; responsePath: string };
const sourceNames: Record<ManualRoutingNativeKind, string> = {
  happy: 'b6200000-0000-4000-8000-000000000122',
  opening: 'b6200000-0000-4000-8000-000000000144',
  blocked: 'b6200000-0000-4000-8000-000000000135',
  missing: 'b6200000-0000-4000-8000-000000000122',
};

/** Test-only original-geometry corpus adapter. SQL/auth/currentness remain in
 * the caller's owned PostgreSQL fixture. Stored responses contribute ONLY the
 * admission qualification evidence; every route/length comes from a new native
 * child invoked by execute, with a new requestId and a fresh owned PF_ROOT.
 *
 * baseRoot is the read-only source corpus generated by the native
 * PathFinder.ManualOrderedTransport.Tests project. WFC_MANUAL_NATIVE_CORPUS
 * overrides its local evidence default for other environments. No production
 * code imports this module. execute calls must be serialized in this process
 * because PF_ROOT/PF_ENGINE_DLL are temporarily changed and always restored.
 */
export async function createManualRoutingNativeFixture(options: { baseRoot?: string; runnerDll?: string } = {}) {
  const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const source = path.resolve(options.baseRoot ?? process.env.WFC_MANUAL_NATIVE_CORPUS
    ?? 'D:/WFC-Test/validation/routing-control-20261115/manual-transport-run-04');
  const runner = path.resolve(options.runnerDll ?? process.env.PF_MODEL_RUNNER_DLL ?? process.env.PF_ENGINE_DLL
    ?? path.join(repository, 'pathfinder-engine/tools/PathFinder.ModelRunner/bin/Debug/net9.0/PathFinder.ModelRunner.dll'));
  const stat = await fs.lstat(runner);
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error('A compiled regular ModelRunner DLL is required for live manual worker verification.');
  const tempParent = path.resolve(os.tmpdir()), root = await fs.mkdtemp(path.join(tempParent, 'wfc-manual-native-'));
  const owner = randomUUID(), ownerPath = path.join(root, '.manual-native-owner');
  await fs.writeFile(ownerPath, owner, { flag: 'wx' });
  const executions: Execution[] = [];
  let environmentBusy = false, disposed = false;
  async function withEnvironment<T>(body: () => Promise<T>): Promise<T> {
    if (disposed || environmentBusy) throw new Error('Live native fixture calls must be serialized and precede disposal.');
    environmentBusy = true;
    const previous = { root: process.env.PF_ROOT, dll: process.env.PF_ENGINE_DLL };
    process.env.PF_ROOT = root; process.env.PF_ENGINE_DLL = runner;
    try { return await body(); }
    finally {
      if (previous.root === undefined) delete process.env.PF_ROOT; else process.env.PF_ROOT = previous.root;
      if (previous.dll === undefined) delete process.env.PF_ENGINE_DLL; else process.env.PF_ENGINE_DLL = previous.dll;
      environmentBusy = false;
    }
  }
  async function dispose() {
    if (disposed) return;
    if (environmentBusy) throw new Error('Wait for the owned native child to join before disposing its fixture.');
    const resolved = path.resolve(root);
    if (!resolved.startsWith(tempParent + path.sep) || !path.basename(resolved).startsWith('wfc-manual-native-')
      || await fs.readFile(ownerPath, 'utf8') !== owner) throw new Error('Refusing cleanup outside the exact owned native fixture.');
    disposed = true; await fs.rm(resolved, { recursive: true, force: false });
  }
  try {
    // Copy only the immutable native inputs. Never copy or read cached routes,
    // generated responses or preparation caches into the new execution root.
    await fs.cp(path.join(source, 'snapshots'), path.join(root, 'snapshots'), { recursive: true, errorOnExist: true, force: false });
    await fs.cp(path.join(source, 'barriers'), path.join(root, 'barriers'), { recursive: true, errorOnExist: true, force: false });
    await fs.mkdir(path.join(root, 'live-worker-evidence'));
    const templates = {} as Record<ManualRoutingNativeKind, EngineInvocation>;
    const qualifications = {} as Record<ManualRoutingNativeKind, ReturnType<typeof mixedBarrierVerifierEvidenceSchema.parse>>;
    for (const kind of Object.keys(sourceNames) as ManualRoutingNativeKind[]) {
      const name = sourceNames[kind];
      templates[kind] = JSON.parse(await fs.readFile(path.join(source, name + '.request.json'), 'utf8')) as EngineInvocation;
      const reference = JSON.parse(await fs.readFile(path.join(source, name + '.response.json'), 'utf8')) as {
        barriers: { qualification: { evidence: unknown } };
      };
      qualifications[kind] = mixedBarrierVerifierEvidenceSchema.parse(reference.barriers.qualification.evidence);
    }
    // Both measured equipment approaches exceed the normal two-metre threshold.
    // The existing 5m partial tray path, S=7m, E=5m, P=10% must yield ceil(26.4)=27m.
    templates.happy.from = { x: .5, y: -3, z: .1 };
    templates.happy.to = { x: 5.5, y: 4, z: .1 };
    templates.missing.manualRouteConstraint = { schemaVersion: 'pathfinder.manual-ordered-route.v1', routeText: '/DOES_NOT_EXIST' };
    const engineIdentity = await withEnvironment(() => mixedBarrierCalculationEngineIdentity({ force: true }));
    const projectId = String(templates.happy.projectId);
    function request(requestId: string, kind: ManualRoutingNativeKind): EngineInvocation {
      if (disposed || !/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i.test(requestId))
        throw new Error('A fresh UUID request identity is required for live native execution.');
      const value = structuredClone(templates[kind]); value.requestId = requestId;
      if (requestId === templates[kind].requestId || executions.some(item => item.requestId === requestId))
        throw new Error('A recorded or already-executed request identity cannot be reused by the live native fixture.');
      return value;
    }
    function protectedOverrides(kind: ManualRoutingNativeKind): BarrierDependencySnapshot {
      const input = templates[kind], base = syntheticBarrierWriteInputs().dependencies;
      const barriers = supportedBarrierRuntimeContextSchema.parse(input.barriers);
      if (barriers.schemaVersion !== 'wfc.pf.barrier-runtime.v2') throw new Error('The live manual corpus requires original mixed barrier evidence.');
      const scope = barriers.binding.scope;
      const intent = supportedBarrierAdmissionIntentSchema.parse({ schemaVersion: 'wfc.pf.barrier-admission-intent.v2', geometryPolicy: MIXED_BARRIER_POLICY, scope,
        expectedRegistryRevision: barriers.binding.registryRevision, expectedSnapshot: barriers.binding.snapshot,
        drillThroughWalls: barriers.binding.policy.drillThroughWalls });
      const from = input.from as { x: number; y: number; z: number }, to = input.to as { x: number; y: number; z: number };
      const numeric = input.options as BarrierDependencySnapshot['options'];
      return { ...base, projectId, model: { id: String(input.modelVersionId), selectionRevision: scope.selectionRevision, contentFingerprint: scope.contentFingerprint },
        artifact: { id: String(input.snapshotId), sha256: String(input.snapshotSha256) },
        preparation: { ...base.preparation, captureFrameId: scope.captureFrameId },
        cableInputs: { ...base.cableInputs, mto: 'Control' },
        from: { ...base.from, point: [from.x, from.y, from.z], captureFrameId: scope.captureFrameId },
        to: { ...base.to, point: [to.x, to.y, to.z], captureFrameId: scope.captureFrameId },
        settings: { ...(input.projectSettings as Pick<BarrierDependencySnapshot['settings'], 'revision' | 'secondaryTrayLength' | 'endConnectionLength' | 'additionalBendingPercent'>),
          connectionGap: String(numeric.connectionToleranceMeters) },
        options: { ...numeric, barrierRouting: intent }, engineIdentity, barriers, barrierQualification: structuredClone(qualifications[kind]) };
    }
    async function execute(input: EngineInvocation, signal: AbortSignal): Promise<EngineResponse> {
      if (input.operation !== 'calculate' || input.schemaVersion !== 'pathfinder.model.runner.v2' || !input.manualRouteConstraint
        || executions.some(item => item.requestId === input.requestId)) throw new Error('Only a new protected manual calculation may use this native fixture.');
      const requestPath = path.join(root, 'live-worker-evidence', input.requestId + '.request.json');
      const responsePath = path.join(root, 'live-worker-evidence', input.requestId + '.response.json');
      await fs.writeFile(requestPath, JSON.stringify(input), { flag: 'wx' });
      let pid = 0;
      const response = await withEnvironment(() => runEngine(input, signal, value => { pid = value; }));
      if (pid <= 0) throw new Error('Live native execution did not observe its owned child process.');
      await fs.writeFile(responsePath, JSON.stringify(response), { flag: 'wx' });
      executions.push({ requestId: input.requestId, pid, status: response.status, requestPath, responsePath });
      return response;
    }
    return { projectId, root, request, protectedOverrides, execute, executions,
      expected: { happy: 27, opening: 10, blocked: null, missing: null } as const, dispose };
  } catch (error) { await dispose(); throw error; }
}
